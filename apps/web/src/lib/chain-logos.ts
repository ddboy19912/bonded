/** The logo for a network, or undefined when there isn't one (the caller draws a lettered disc). */
export function chainLogo(chainId: number | undefined): string | undefined {
  if (chainId === undefined) return undefined;
  if (chainId === robinhoodTestnet.id) return "/brand/chains/networks/robinhood.svg";
  const key = LOGOS[chainId];
  return key ? `/brand/chains/networks/${key}.svg` : undefined;
}
